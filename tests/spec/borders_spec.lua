local borders = require "popup.borders"

describe("borders.box", function()
  it("follows CSS box rules", function()
    assert.are.same({ 0, 0, 0, 0 }, borders.box(nil))
    assert.are.same({ 1, 1, 1, 1 }, borders.box {})
    assert.are.same({ 2, 2, 2, 2 }, borders.box { 2 })
    assert.are.same({ 1, 2, 1, 2 }, borders.box { 1, 2 })
    assert.are.same({ 1, 2, 3, 2 }, borders.box { 1, 2, 3 })
    assert.are.same({ 1, 2, 3, 4 }, borders.box { 1, 2, 3, 4 })
  end)
end)

describe("borders.expand_chars", function()
  it("fills from one, two or four entries", function()
    assert.are.same({ "#", "#", "#", "#", "#", "#", "#", "#" }, borders.expand_chars { "#" })
    assert.are.same({ "-", "|", "-", "|", "┌", "┐", "┘", "└" }, borders.expand_chars { "-", "|" })
    assert.are.same(borders.DEFAULT_CHARS, borders.expand_chars(nil))
  end)
end)

describe("borders.to_native", function()
  it("returns none when every side is 0", function()
    assert.are.equal("none", borders.to_native(nil, { 0, 0, 0, 0 }))
  end)

  it("maps Vim order to the native order", function()
    local b = borders.to_native({ "t", "r", "b", "l", "1", "2", "3", "4" }, { 1, 1, 1, 1 })
    assert.are.same({ "1", "t", "2", "r", "3", "b", "4", "l" }, b)
  end)

  it("drops a side and the corners that touch it", function()
    local b = borders.to_native({ "t", "r", "b", "l", "1", "2", "3", "4" }, { 0, 1, 1, 1 })
    assert.are.same({ "", "", "", "r", "3", "b", "4", "l" }, b)
  end)

  it("attaches highlight groups per side", function()
    local b = borders.to_native({ "-", "|", "-", "|", "+", "+", "+", "+" }, { 1, 1, 1, 1 }, { "T", "R", "B", "L" })
    assert.are.same({ "+", "T" }, b[1])
    assert.are.same({ "|", "R" }, b[4])
    assert.are.same({ "-", "B" }, b[6])
  end)
end)

describe("borders.resolve", function()
  it("explicit beats configured beats winborder", function()
    assert.are.equal("single", borders.resolve { explicit = "single", configured = "double", winborder = "bold" })
    assert.are.equal("double", borders.resolve { configured = "double", winborder = "bold" })
    assert.are.equal("bold", borders.resolve { configured = "auto", winborder = "bold" })
  end)

  it("falls back to rounded", function()
    assert.are.equal("rounded", borders.resolve { configured = "auto", winborder = "" })
    assert.are.equal("rounded", borders.resolve {})
  end)

  it("session-mgr style treats winborder=none as unset, devdocs style keeps it", function()
    assert.are.equal("rounded", borders.resolve { winborder = "none", none_is_rounded = true })
    assert.are.equal("none", borders.resolve { winborder = "none" })
  end)
end)
